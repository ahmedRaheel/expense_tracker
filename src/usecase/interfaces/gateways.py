from datetime import date
from decimal import Decimal
from typing import Protocol, Any
from uuid import UUID
from src.usecase.context.identity import CurrentUser
from src.usecase.dto.auth import RegisterRequest, LoginRequest, RefreshRequest, TokenPair, UserDTO
from src.usecase.dto.categories import CategoryCreate, CategoryDTO
from src.usecase.dto.expenses import ExpenseCreate, ExpensePatch, ExpenseDTO, ExpenseResults
from src.usecase.dto.reports import MonthlyReport
from src.usecase.dto.notifications import NotificationDTO
from src.usecase.dto.imports import ImportJobDTO
from src.usecase.dto.receipts import ReceiptUploadURL, ReceiptConfirm, ReceiptDownload

class AsyncUpload(Protocol):
    filename: str | None
    async def read(self, size: int = -1) -> bytes: ...
    async def close(self) -> None: ...

class AuthenticationPort(Protocol):
    async def register(self, payload: RegisterRequest) -> UserDTO: ...
    async def login(self, payload: LoginRequest) -> TokenPair: ...
    async def refresh(self, payload: RefreshRequest) -> TokenPair: ...
    async def logout(self, payload: RefreshRequest, actor: CurrentUser) -> None: ...

class CategoryPort(Protocol):
    async def create(self, actor: CurrentUser, payload: CategoryCreate) -> CategoryDTO: ...
    async def list(self, actor: CurrentUser) -> list[CategoryDTO]: ...

class ExpensePort(Protocol):
    async def create(self, actor: CurrentUser, payload: ExpenseCreate, key: str) -> tuple[dict, bool]: ...
    async def get(self, actor: CurrentUser, expense_id: UUID) -> ExpenseDTO: ...
    async def list(self, actor: CurrentUser, *, cursor: str | None, limit: int, category_id: UUID | None,
                   date_from: date | None, date_to: date | None, min_amount: Decimal | None,
                   max_amount: Decimal | None, currency: str | None, q: str | None) -> ExpenseResults: ...
    async def update(self, actor: CurrentUser, expense_id: UUID, expected_version: int, payload: ExpensePatch) -> ExpenseDTO: ...
    async def delete(self, actor: CurrentUser, expense_id: UUID) -> None: ...

class ReportPort(Protocol):
    async def monthly(self, actor: CurrentUser, year: int, month: int) -> MonthlyReport: ...

class NotificationPort(Protocol):
    async def list(self, actor: CurrentUser, limit: int) -> list[NotificationDTO]: ...

class ImportPort(Protocol):
    async def submit(self, actor: CurrentUser, file: AsyncUpload) -> ImportJobDTO: ...
    async def status(self, actor: CurrentUser, job_id: UUID, error_after: int, error_limit: int) -> ImportJobDTO: ...

class ReceiptPort(Protocol):
    async def upload_url(self, actor: CurrentUser, expense_id: UUID, content_type: str) -> ReceiptUploadURL: ...
    async def confirm(self, actor: CurrentUser, expense_id: UUID, payload: ReceiptConfirm) -> ReceiptDownload: ...
    async def download(self, actor: CurrentUser, expense_id: UUID) -> ReceiptDownload: ...

class StoragePort(Protocol):
    async def upload_post(self, key: str, content_type: str) -> dict: ...
    async def validate_object(self, key: str, expected_type: str) -> int: ...
    async def download_url(self, key: str) -> str: ...
    async def delete_object(self, key: str) -> None: ...
